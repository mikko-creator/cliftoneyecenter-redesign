// write-architecture.mjs — docs/SITE-ARCHITECTURE.md, generated from the crawl evidence (never typed):
// the live site's full URL tree, page types, navigation, forms, redirects, orphans and link graph.
//   node tools/write-architecture.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const J = (f) => JSON.parse(fs.readFileSync(path.join(PROJ, f), 'utf8'));
const site = J('audit/site-inventory.json');
const content = J('audit/content-inventory.json');
const arch = J('audit/architecture.json');
const chrome = J('src/content/chrome.json');
const redirects = fs.existsSync(path.join(PROJ, 'audit/redirects.json')) ? J('audit/redirects.json').redirects : [];
const failures = J('audit/failures.json').items || [];
const links = fs.existsSync(path.join(PROJ, 'audit/link-graph.json')) ? J('audit/link-graph.json') : null;
const ORIGIN = site.origin;
const pathOf = (u) => { try { return new URL(u).pathname.replace(/\/?$/, '/'); } catch { return u; } };
const byPath = new Map(content.pages.map((p) => [pathOf(p.url), p]));

/* URL tree */
const root = { name: '/', kids: new Map(), page: byPath.get('/') };
for (const [p, page] of byPath) {
  if (p === '/') continue;
  const segs = p.replace(/^\/|\/$/g, '').split('/');
  let node = root;
  segs.forEach((s, i) => {
    if (!node.kids.has(s)) node.kids.set(s, { name: s, kids: new Map(), page: null });
    node = node.kids.get(s);
    if (i === segs.length - 1) node.page = page;
  });
}
const lines = [];
const title = (pg) => (pg ? ' — ' + String((pg.h1 && pg.h1[0]) || pg.title || '').replace(/\s+/g, ' ').slice(0, 70) + '  `' + pg.pageType + '`' : '  *(no page at this path — folder only)*');
function walk(node, depth, pre) {
  const kids = [...node.kids.values()].sort((a, b) => (b.kids.size - a.kids.size) || a.name.localeCompare(b.name));
  for (const k of kids) {
    lines.push('  '.repeat(depth) + '- `' + pre + k.name + '/`' + title(k.page));
    walk(k, depth + 1, pre + k.name + '/');
  }
}
walk(root, 0, '/');

const types = Object.entries(arch.pageTypes).sort((a, b) => b[1] - a[1]).map(([t, n]) => '| ' + t + ' | ' + n + ' |').join('\n');
const depthH = Object.entries(arch.urlDepthHistogram).map(([d, n]) => '| ' + d + ' | ' + n + ' |').join('\n');
const top = root.kids.size;
const nav = chrome.nav.map((n) => '- **' + n.label + '** → `' + n.href + '`' + ((n.children || []).length ? '\n' + n.children.map((c) => '  - ' + c.label + ' → `' + c.href + '`').join('\n') : '')).join('\n');
const foot = chrome.footerLinks.map((l) => '`' + l.href + '` ' + l.label).join(' · ');
const forms = (arch.formsByAction || []).map((f) => '| `' + f.action + '` | ' + f.pages.length + ' | ' + [...new Set(f.fields)].filter((x) => !/^(submit|ak_hp|input_19)/.test(x)).length + ' |').join('\n');
const orphans = (arch.orphanPages || []).map((u) => '- `' + pathOf(u) + '`').join('\n');
const f404 = failures.filter((f) => f.stage === 'crawl:page').map((f) => '- `' + pathOf(f.target) + '` — ' + f.reason).join('\n');
const redir = redirects.map((r) => '| `' + r.from + '` | `' + r.to + '` | ' + r.why + ' |').join('\n');
const inbound = new Map();
if (links && links.edges) for (const e of links.edges) { const t = pathOf(e.to || e[1]); inbound.set(t, (inbound.get(t) || 0) + 1); }
const hubs = [...inbound].sort((a, b) => b[1] - a[1]).slice(0, 15).map(([p, n]) => '| `' + p + '` | ' + n + ' |').join('\n');

const md = `# Site architecture — ${ORIGIN}

Generated by \`tools/write-architecture.mjs\` from the crawl of ${String(site.generated || '').slice(0, 10)} (\`audit/site-inventory.json\`, \`audit/content-inventory.json\`, \`audit/architecture.json\`). Nothing here is typed by hand; re-run the script after a re-crawl.

## At a glance

| | |
|---|---|
| HTML pages crawled | **${site.counts.html}** (of ${site.counts.pages} URLs discovered; ${site.counts.failed} failed — all live-site 404s, listed below) |
| Discovered from | sitemap (${site.discovery.sitemapUrlCount} URLs) + breadth-first link crawl · robots.txt honoured: ${site.discovery.robotsHonoured} · truncated: ${site.truncated} |
| Top-level sections | ${top} |
| Redirect aliases the live site serves | ${redirects.filter((r) => /(live site)/.test(r.why)).length} (carried forward) + ${redirects.filter((r) => !/(live site)/.test(r.why)).length} added for source links that 404, see Redirects |
| Source platform | WordPress + Beaver Builder theme by the practice's former agency (audit/source-cms.json) |
| Rebuild | same URL for every page: \`<path>/index.html\` in \`dist/\` |

### Page types (as classified by sr-extract)

| type | pages |
|---|---|
${types}

### URL depth

| depth | pages |
|---|---|
${depthH}

## Navigation

Primary menu (identical on all 287 pages):

${nav}

Footer links: ${foot}

Utility links: ${chrome.utilLinks.map((l) => '`' + l.href + '` ' + l.label).join(' · ')}

## Full URL tree

Every page the crawl found, grouped by path. \`type\` is the extractor's page type.

- \`/\` — ${String(root.page ? root.page.h1[0] : '')} \`home\`
${lines.join('\n')}

## Forms

| action (source) | pages | distinct fields |
|---|---|---|
${forms}

Most pages carry the site-wide appointment widget; the contact-us pages carry their own forms. In the rebuild every form is re-created from the labels, options and required markers the source printed, and posts nowhere until a backend is wired (see DEPLOY.md).

## Most-linked pages (inbound internal links)

| page | inbound links |
|---|---|
${hubs || '| (link graph not available) | |'}

## Orphans (no inbound links)

${orphans}

16 of these are WordPress plumbing (empty archives, slideshow stubs, raw templates, the 404 body): kept at their URLs, marked \`noindex, follow\`, left out of sitemap.xml. \`/testimonial/dr-brooks-genuinely-cares-about-her-patients/\` is a real patient testimonial and is kept indexable.

## Live-site 404s the crawl hit

${f404}

## Redirects

| from | to | why |
|---|---|---|
${redir}

Emitted in the build as \`dist/_redirects\` (Netlify / Cloudflare Pages) and \`dist/.htaccess\` (Apache).
`;
fs.writeFileSync(path.join(PROJ, 'docs/SITE-ARCHITECTURE.md'), md);
console.log('docs/SITE-ARCHITECTURE.md', md.length, 'chars,', lines.length + 1, 'tree lines');
